#!/usr/bin/env python3
"""Copy capability-detail content into the repo.

Source: <SRC>/<page>/content.json and <SRC>/<page>/images/
Target: src/content/<page>.json and public/images/details/<page>/

- Pages with no content.json are skipped and reported.
- Items whose photo_file is null keep photo_file null (rendered as text only).
- Photos are optimised offline to the NFR-3 budget (<=1200 px long edge,
  <=150 KB JPEG). Their width/height are recorded as photo_width/photo_height
  so the page can set explicit dimensions.
- Optional: <SRC>/ATTRIBUTIONS.md is copied to src/content/ATTRIBUTIONS.md.

Usage: python3 scripts/sync_content.py [SRC]
Needs Pillow only when a photo exists. This is a dev-time script, not an npm dep.
"""
import io
import json
import os
import shutil
import sys

PAGES = ["surveys", "geotechnical", "geophysical", "geological-mapping", "environmental", "health-safety"]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/aiciv/exports/atlas-gcc-content"
MAX_EDGE = 1200
MAX_BYTES = 150 * 1024


def optimise(src_path, dst_path):
    from PIL import Image  # imported lazily: only needed when photos exist

    img = Image.open(src_path)
    img = img.convert("RGB")
    img.thumbnail((MAX_EDGE, MAX_EDGE))
    for quality in (85, 80, 75, 70, 65, 60, 55, 50):
        buf = io.BytesIO()
        img.save(buf, "JPEG", quality=quality, optimize=True, progressive=True)
        if buf.tell() <= MAX_BYTES:
            break
    with open(dst_path, "wb") as f:
        f.write(buf.getvalue())
    return img.size, buf.tell()


def write_index(pages):
    """Generate src/content/pages.generated.ts importing only pages that exist."""
    ident = lambda p: "c_" + p.replace("-", "_")
    lines = ["// GENERATED by scripts/sync_content.py. Do not edit by hand.", "import type { DetailCard } from './types';"]
    for p in pages:
        lines.append(f"import {ident(p)} from './{p}.json';")
    lines.append("")
    lines.append("export const DETAIL_CONTENT: Record<string, DetailCard[]> = {")
    for p in pages:
        lines.append(f"  '{p}': {ident(p)} as DetailCard[],")
    lines.append("};")
    with open(os.path.join(ROOT, "src", "content", "pages.generated.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # Small heading -> slug map for the service pages (keeps the full JSON out of their bundles).
    links = {}
    for p in pages:
        with open(os.path.join(ROOT, "src", "content", f"{p}.json"), encoding="utf-8") as f:
            links[p] = {c["card_heading"]: c["card_slug"] for c in json.load(f)}
    with open(os.path.join(ROOT, "src", "content", "card-links.generated.ts"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/sync_content.py. Do not edit by hand.\n")
        f.write("export const CARD_LINKS: Record<string, Record<string, string>> = ")
        f.write(json.dumps(links, ensure_ascii=False, indent=2))
        f.write(";\n")


def main():
    report = {"pages": {}, "skipped": [], "over_budget": []}
    for page in PAGES:
        cpath = os.path.join(SRC, page, "content.json")
        if not os.path.exists(cpath):
            report["skipped"].append(page)
            continue
        with open(cpath, encoding="utf-8") as f:
            cards = json.load(f)
        img_out = os.path.join(ROOT, "public", "images", "details", page)
        with_photo, without_photo = 0, 0
        for card in cards:
            for item in card["items"]:
                pf = item.get("photo_file")
                # photo_file may be "name.jpg" (inside images/) or "images/name.jpg" (relative to the page dir).
                src_img = None
                if pf:
                    for cand in (os.path.join(SRC, page, pf), os.path.join(SRC, page, "images", os.path.basename(pf))):
                        if os.path.exists(cand):
                            src_img = cand
                            break
                if src_img:
                    os.makedirs(img_out, exist_ok=True)
                    base = os.path.splitext(os.path.basename(pf))[0] + ".jpg"
                    (w, h), size = optimise(src_img, os.path.join(img_out, base))
                    item["photo_file"] = base
                    item["photo_width"], item["photo_height"] = w, h
                    if size > MAX_BYTES:
                        report["over_budget"].append(f"{page}/{base} {size}B")
                    with_photo += 1
                else:
                    if pf:
                        report.setdefault("photo_file_missing_on_disk", []).append(f"{page}/{pf}")
                    item["photo_file"] = None
                    item.pop("photo_width", None)
                    item.pop("photo_height", None)
                    without_photo += 1
        out = os.path.join(ROOT, "src", "content", f"{page}.json")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            json.dump(cards, f, ensure_ascii=False, indent=2)
            f.write("\n")
        report["pages"][page] = {"cards": len(cards), "with_photo": with_photo, "without_photo": without_photo}
    write_index(list(report["pages"].keys()))
    attr = os.path.join(SRC, "ATTRIBUTIONS.md")
    if os.path.exists(attr):
        shutil.copyfile(attr, os.path.join(ROOT, "src", "content", "ATTRIBUTIONS.md"))
        report["attributions"] = True
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
